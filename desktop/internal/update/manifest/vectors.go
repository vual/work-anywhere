package manifest

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"strings"
)

// TestVectorKeyID names the deterministic key used only by vectors.json. It
// must never appear in TrustedKeys.
const TestVectorKeyID = "waw-test-vectors"

// TestVectorKey returns the deterministic Ed25519 key for vectors.json.
func TestVectorKey() ed25519.PrivateKey {
	seed := sha256.Sum256([]byte("work-anywhere update manifest test vectors"))
	return ed25519.NewKeyFromSeed(seed[:])
}

// Vectors is the shape of docs/self-update/vectors.json.
type Vectors struct {
	Description string            `json:"description"`
	TrustedKeys map[string]string `json:"trustedKeys"`
	Manifests   []ManifestVector  `json:"manifests"`
	Versions    []VersionVector   `json:"versions"`
	Mirrors     []MirrorVector    `json:"mirrors"`
}

type ManifestVector struct {
	Name                 string `json:"name"`
	Raw                  string `json:"raw"`
	ExpectError          string `json:"expectError,omitempty"`
	ExpectVersion        string `json:"expectVersion,omitempty"`
	ExpectAPKVersionCode int64  `json:"expectApkVersionCode,omitempty"`
}

type VersionVector struct {
	Candidate string `json:"candidate"`
	Current   string `json:"current"`
	Newer     bool   `json:"newer"`
	Invalid   bool   `json:"invalid,omitempty"`
}

type MirrorVector struct {
	MirrorBase  string `json:"mirrorBase"`
	ManifestURL string `json:"manifestUrl,omitempty"`
	AssetIn     string `json:"assetIn,omitempty"`
	AssetOut    string `json:"assetOut,omitempty"`
	Invalid     bool   `json:"invalid,omitempty"`
}

func samplePayload() Payload {
	hash := strings.Repeat("ab", 32)
	return Payload{
		Channel:     ChannelStable,
		Version:     "0.3.0",
		Tag:         "v0.3.0",
		PublishedAt: "2026-11-10T08:00:00Z",
		NotesURL:    "https://github.com/vual/work-anywhere/releases/tag/v0.3.0",
		Assets: map[string]Asset{
			AssetWindowsSetup: {
				Name: "work-anywhere-setup-0.3.0.exe", URL: ReleasesPrefix + "download/v0.3.0/work-anywhere-setup-0.3.0.exe",
				Size: 9123456, SHA256: hash,
			},
			AssetWindowsPortable: {
				Name: "work-anywhere-0.3.0-windows-amd64.exe", URL: ReleasesPrefix + "download/v0.3.0/work-anywhere-0.3.0-windows-amd64.exe",
				Size: 21234567, SHA256: hash,
			},
			AssetAndroidAPK: {
				Name: "work-anywhere-0.3.0-android.apk", URL: ReleasesPrefix + "download/v0.3.0/work-anywhere-0.3.0-android.apk",
				Size: 31234567, SHA256: hash, PackageName: "io.workanywhere.work_anywhere", VersionCode: 87,
				SigningCertSHA256: strings.Repeat("cd", 32),
			},
		},
	}
}

// BuildVectors deterministically generates vectors.json.
func BuildVectors() ([]byte, error) {
	key := TestVectorKey()
	sign := func(mutate func(*Payload)) (string, error) {
		payload := samplePayload()
		if mutate != nil {
			mutate(&payload)
		}
		raw, err := json.Marshal(payload)
		if err != nil {
			return "", err
		}
		envelope, err := Sign(raw, TestVectorKeyID, key)
		return string(envelope), err
	}
	editEnvelope := func(raw string, edit func(*Envelope)) (string, error) {
		var envelope Envelope
		if err := json.Unmarshal([]byte(raw), &envelope); err != nil {
			return "", err
		}
		edit(&envelope)
		out, err := json.MarshalIndent(envelope, "", "  ")
		return string(out), err
	}

	valid, err := sign(nil)
	if err != nil {
		return nil, err
	}
	vectors := Vectors{
		Description: "Generated by `go run ./internal/tools/updatemanifest vectors`; signed with a test-only key. Desktop internal/update/manifest and Mobile core/update tests both read this file.",
		TrustedKeys: map[string]string{TestVectorKeyID: base64.RawURLEncoding.EncodeToString(key.Public().(ed25519.PublicKey))},
	}
	vectors.Manifests = append(vectors.Manifests, ManifestVector{Name: "valid", Raw: valid, ExpectVersion: "0.3.0", ExpectAPKVersionCode: 87})

	type caseDef struct {
		name   string
		code   string
		mutate func(*Payload)
	}
	for _, c := range []caseDef{
		{"bad version", CodeInvalid, func(p *Payload) { p.Version, p.Tag = "0.3", "v0.3" }},
		{"prerelease version", CodeInvalid, func(p *Payload) { p.Version, p.Tag = "0.3.0-beta.1", "v0.3.0-beta.1" }},
		{"tag mismatch", CodeInvalid, func(p *Payload) { p.Tag = "v0.3.1" }},
		{"wrong channel", CodeInvalid, func(p *Payload) { p.Channel = "beta" }},
		{"http asset url", CodeInvalid, func(p *Payload) {
			asset := p.Assets[AssetWindowsSetup]
			asset.URL = "http://example.com/setup.exe"
			p.Assets[AssetWindowsSetup] = asset
		}},
		{"oversized asset", CodeInvalid, func(p *Payload) {
			asset := p.Assets[AssetAndroidAPK]
			asset.Size = MaxAssetBytes + 1
			p.Assets[AssetAndroidAPK] = asset
		}},
		{"apk missing signer", CodeInvalid, func(p *Payload) {
			asset := p.Assets[AssetAndroidAPK]
			asset.SigningCertSHA256 = ""
			p.Assets[AssetAndroidAPK] = asset
		}},
	} {
		raw, err := sign(c.mutate)
		if err != nil {
			return nil, err
		}
		vectors.Manifests = append(vectors.Manifests, ManifestVector{Name: c.name, Raw: raw, ExpectError: c.code})
	}

	type envelopeDef struct {
		name string
		code string
		edit func(*Envelope)
	}
	for _, c := range []envelopeDef{
		{"tampered payload", CodeSignatureInvalid, func(e *Envelope) {
			payload, _ := base64.RawURLEncoding.DecodeString(e.Payload)
			e.Payload = base64.RawURLEncoding.EncodeToString([]byte(strings.Replace(string(payload), "0.3.0", "9.3.0", 1)))
		}},
		{"unknown key id", CodeSignatureInvalid, func(e *Envelope) { e.KeyID = "waw-unknown" }},
		{"bad signature", CodeSignatureInvalid, func(e *Envelope) {
			signature, _ := base64.RawURLEncoding.DecodeString(e.Signature)
			signature[0] ^= 0xff
			e.Signature = base64.RawURLEncoding.EncodeToString(signature)
		}},
		{"wrong format version", CodeInvalid, func(e *Envelope) { e.FormatVersion = 2 }},
	} {
		raw, err := editEnvelope(valid, c.edit)
		if err != nil {
			return nil, err
		}
		vectors.Manifests = append(vectors.Manifests, ManifestVector{Name: c.name, Raw: raw, ExpectError: c.code})
	}
	vectors.Manifests = append(vectors.Manifests, ManifestVector{Name: "not json", Raw: "not json", ExpectError: CodeInvalid})

	vectors.Versions = []VersionVector{
		{Candidate: "0.3.0", Current: "0.2.0", Newer: true},
		{Candidate: "0.3.0", Current: "0.3.0", Newer: false},
		{Candidate: "0.3.0", Current: "0.4.0", Newer: false},
		{Candidate: "0.10.0", Current: "0.9.9", Newer: true},
		{Candidate: "1.0.0", Current: "1.0.0-rc.1", Newer: true},
		{Candidate: "1.0.0", Current: "1.0.0+build.5", Newer: false},
		{Candidate: "0.3.0", Current: "dev", Invalid: true},
		{Candidate: "0.3.0", Current: "0.3", Invalid: true},
	}
	vectors.Mirrors = []MirrorVector{
		{MirrorBase: "", ManifestURL: DefaultURL, AssetIn: ReleasesPrefix + "download/v0.3.0/a.apk", AssetOut: ReleasesPrefix + "download/v0.3.0/a.apk"},
		{MirrorBase: "https://mirror.example.com/waw/", ManifestURL: "https://mirror.example.com/waw/latest/download/update-manifest.json",
			AssetIn: ReleasesPrefix + "download/v0.3.0/a.apk", AssetOut: "https://mirror.example.com/waw/download/v0.3.0/a.apk"},
		{MirrorBase: "http://mirror.example.com", Invalid: true},
		{MirrorBase: "https://mirror.example.com/?x=1", Invalid: true},
	}
	out, err := json.MarshalIndent(vectors, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}
